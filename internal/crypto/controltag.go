package crypto

import (
	"crypto/subtle"
	"encoding/binary"
	"errors"

	"github.com/zeebo/blake3"
)

// Метка подлинности служебных кадров.
//
// Пакеты данных защищены шифрованием ChaCha20-Poly1305, которое само по себе
// содержит метку подлинности: подделать пакет нельзя. Служебные кадры —
// сообщение о ротации, подтверждение ротации и сообщение об ошибке — шли
// открытым текстом и никак не были связаны с сеансовым ключом.
//
// Чем это плохо. Кадры ходят внутри уже установленной сессии, но сама сессия
// живёт поверх обычного TCP, без защиты канала. Тот, кто вклинился в
// соединение, не может пройти рукопожатие (для этого нужен закрытый ключ
// устройства), но может подменить или вбросить служебный кадр. Проверено
// опытом: вброшенное подтверждение ротации шлюз принимал и применял ротацию,
// тогда как устройство её не применяло. Ключи расходились, устройство больше
// не могло расшифровать ни одного кадра и в итоге отзывалось.
//
// Почему метка на сеансовом ключе, а не подпись. Подпись ECDSA стоит 22 мс на
// ESP32-C6 и 170 мс на ESP32-S3, а ротация происходит каждые пять минут либо
// каждые триста пакетов. Метка на BLAKE3 обходится в 18 микросекунд — в
// тысячу раз дешевле. Доказывать авторство третьей стороне здесь не нужно:
// обе стороны знают сеансовый ключ, а посторонний не знает, и этого
// достаточно.
//
// Что входит в метку и почему:
//
//   - сеансовый ключ — без него метку не вычислить;
//   - тип кадра — иначе метку от подтверждения можно было бы переставить на
//     сообщение об ошибке;
//   - номер шага ротации — привязывает метку к конкретному шагу, так что
//     подтверждение прошлого шага не подойдёт для следующего;
//   - содержимое кадра — защищает сами данные от подмены.
//
// Разделитель области не даёт использовать эту метку там, где ключ участвует
// в других вычислениях, и наоборот.

// ControlTagSize — длина метки в байтах.
//
// Шестнадцати байт достаточно: чтобы подобрать метку наугад, нужно в среднем
// 2^127 попыток, а каждая попытка требует отдельного кадра по сети. При этом
// каждый лишний байт — это байт в эфире на устройстве с батарейным питанием.
const ControlTagSize = 16

const controlTagSeparator = "lacert-control-v1"

// ErrControlTagMismatch возвращается, когда метка не сошлась: кадр подделан,
// повреждён или пришёл от того, кто не знает сеансового ключа.
var ErrControlTagMismatch = errors.New("control frame authentication tag mismatch")

// ComputeControlTag вычисляет метку подлинности служебного кадра.
//
// frameType — тип кадра из internal/wire, iteration — номер шага ротации
// (ноль для кадров, к ротации не относящихся), body — содержимое кадра без
// метки.
func ComputeControlTag(sessionKey []byte, frameType byte, iteration uint64, body []byte) []byte {
	h := blake3.New()
	h.Write(sessionKey)
	h.Write([]byte{frameType})
	var it [8]byte
	binary.BigEndian.PutUint64(it[:], iteration)
	h.Write(it[:])
	h.Write(body)
	h.Write([]byte(controlTagSeparator))
	return h.Sum(nil)[:ControlTagSize]
}

// VerifyControlTag проверяет метку служебного кадра.
//
// Сравнение идёт за постоянное время: иначе по времени ответа можно было бы
// подбирать метку побайтово, а это заметно дешевле полного перебора.
func VerifyControlTag(sessionKey []byte, frameType byte, iteration uint64, body, tag []byte) error {
	if len(tag) != ControlTagSize {
		return ErrControlTagMismatch
	}
	want := ComputeControlTag(sessionKey, frameType, iteration, body)
	if subtle.ConstantTimeCompare(want, tag) != 1 {
		return ErrControlTagMismatch
	}
	return nil
}
