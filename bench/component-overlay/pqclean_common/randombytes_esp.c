// randombytes_esp.c — источник случайности для PQClean на ESP32.
//
// PQClean объявляет PQCLEAN_randombytes, но реализацию оставляет платформе:
// в поставке лежит вариант для настольных систем, читающий из системного
// генератора. Здесь используется аппаратный генератор ESP32.
//
// Важное условие: esp_fill_random даёт криптостойкие значения, только когда
// работает радиомодуль (WiFi или Bluetooth) либо включён источник энтропии.
// Прошивка замеров радио не поднимает, поэтому её значения годятся для
// измерения времени, но не для настоящих ключей. Для боевой прошивки это
// существенно, для замеров — нет: время операции от качества случайности
// не зависит.
#include <stddef.h>
#include <stdint.h>
#include "esp_random.h"
#include "randombytes.h"

int PQCLEAN_randombytes(uint8_t *output, size_t n) {
    esp_fill_random(output, n);
    return 0;
}
